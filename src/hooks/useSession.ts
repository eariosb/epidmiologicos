'use client';

import { useEffect, useState, useCallback } from 'react';
import {
  getActiveSession,
  listCaptures,
  saveCapture,
  deleteCapture,
  updateCapture,
  addVisitedSection,
  listAllSessions,
  setActiveSessionId,
  deleteSession as deleteStoredSession,
  addQuestion as addQuestionToStore,
  updateQuestion,
  deleteQuestion,
  endActiveSession,
  startNewSession,
  onSessionChanged,
  ACTIVE_SESSION_KEY,
  SESSION_CHANGED_KEY,
  type Capture,
  type CaptureType,
  type Session,
} from '@/lib/session-store';

export function useSession() {
  const [session, setSession] = useState<Session | null>(null);
  const [captures, setCaptures] = useState<Capture[]>([]);
  const [allSessions, setAllSessions] = useState<Session[]>([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  const refresh = useCallback(async () => {
    try {
      const [s, c, a] = await Promise.all([getActiveSession(), listCaptures(), listAllSessions()]);
      setSession(s);
      setCaptures(c);
      setAllSessions(a);
      setError(null);
    } catch {
      // IDB failure or quota problems must surface, not hang on "Cargando…".
      setError('No se pudo leer la información de la sesión.');
    } finally {
      setLoading(false);
    }
  }, []);

  // Every session mutation notifies subscribers, so each component using
  // this hook (toolbar, manager, tracker) sees the same session state.
  useEffect(() => {
    refresh();
    const unsubscribe = onSessionChanged(() => {
      void refresh();
    });
    // Cross-tab sync: the store bumps SESSION_CHANGED_KEY on every write
    // and the active-session pointer lives in localStorage, so a second
    // tab (presenter view, second screen) refreshes on the storage event.
    const onStorage = (e: StorageEvent) => {
      if (e.key === SESSION_CHANGED_KEY || e.key === ACTIVE_SESSION_KEY) {
        void refresh();
      }
    };
    window.addEventListener('storage', onStorage);
    return () => {
      unsubscribe();
      window.removeEventListener('storage', onStorage);
    };
  }, [refresh]);

  /** Runs a mutation and surfaces storage failures (quota, IDB errors)
   *  in the error state instead of leaking unhandled rejections. */
  const run = useCallback(
    async (op: () => Promise<unknown>) => {
      try {
        await op();
        await refresh();
      } catch (err) {
        setError(err instanceof Error ? err.message : 'Error de almacenamiento');
      }
    },
    [refresh],
  );

  const addCapture = useCallback(
    async (dataUrl: string, opts: Partial<Capture> = {}) => {
      const type: CaptureType = opts.type ?? 'other';
      // thumbnail is generated by the store (real downscale, not a copy).
      try {
        const capture = await saveCapture({
          name: opts.name ?? `Captura ${captures.length + 1}`,
          dataUrl,
          type,
          tags: opts.tags ?? [],
          sourceSection: opts.sourceSection,
          sourceModuleSlug: opts.sourceModuleSlug,
          timestamp: Date.now(),
        });
        await refresh();
        return capture;
      } catch (err) {
        setError(err instanceof Error ? err.message : 'Error de almacenamiento');
        return null;
      }
    },
    [captures.length, refresh],
  );

  const removeCapture = useCallback(
    (id: string) => run(() => deleteCapture(id)),
    [run],
  );

  const editCapture = useCallback(
    (id: string, patch: Partial<Capture>) => run(() => updateCapture(id, patch)),
    [run],
  );

  const visit = useCallback(
    (slug: string, title: string) => run(() => addVisitedSection(slug, title)),
    [run],
  );

  const switchSession = useCallback(
    (id: string) => run(() => setActiveSessionId(id)),
    [run],
  );

  const removeSession = useCallback(
    (id: string) => run(() => deleteStoredSession(id)),
    [run],
  );

  const addQuestion = useCallback(
    (text: string) => run(() => addQuestionToStore(text)),
    [run],
  );

  const resolveQuestion = useCallback(
    (id: string, resolved: boolean) => run(() => updateQuestion(id, { resolved })),
    [run],
  );

  const removeQuestion = useCallback(
    (id: string) => run(() => deleteQuestion(id)),
    [run],
  );

  const endSession = useCallback(() => run(endActiveSession), [run]);

  const newSession = useCallback(
    (title: string) => run(() => startNewSession(title)),
    [run],
  );

  return {
    session,
    captures,
    allSessions,
    loading,
    error,
    refresh,
    addCapture,
    removeCapture,
    editCapture,
    visit,
    switchSession,
    removeSession,
    addQuestion,
    resolveQuestion,
    removeQuestion,
    endSession,
    newSession,
  };
}
